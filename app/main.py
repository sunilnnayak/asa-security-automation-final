@app.post("/scans/{scan_id}/share", status_code=201)
def create_shared_report(
    scan_id: int,
    payload: ShareCreate,
    request: Request,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    scan = db.query(models.ScanResult).filter(
        models.ScanResult.id == scan_id,
        models.ScanResult.owner_id == current_user.id,
    ).first()
    if not scan:
        raise HTTPException(status_code=404, detail="Scan not found")
    if payload.password is not None and len(payload.password.encode("utf-8")) > 72:
        raise HTTPException(status_code=422, detail="Share password must be at most 72 UTF-8 bytes")

    # The raw bearer capability is returned once; only its SHA-256 digest is stored.
    raw_token = secrets.token_urlsafe(32)
    token_digest = hashlib.sha256(raw_token.encode("utf-8")).hexdigest()
    share = models.SharedReport(
        scan_id=scan.id,
        token_hash=token_digest,
        password_hash=get_password_hash(payload.password) if payload.password else None,
        expires_at=datetime.utcnow() + timedelta(hours=24),
    )
    db.add(share)
    db.commit()
    return {"share_url": PUBLIC_BASE_URL + f"/share/{raw_token}"}


@app.get("/share/{token}", response_model=SharedScanOut)
def get_shared_report(
    token: str,
    password: Optional[str] = None,
    db: Session = Depends(get_db),
):
    token_digest = hashlib.sha256(token.encode("utf-8")).hexdigest()
    share = db.query(models.SharedReport).filter(
        models.SharedReport.token_hash == token_digest
    ).first()
    if not share or share.expires_at <= datetime.utcnow():
        raise HTTPException(status_code=404, detail="Shared report not found or expired")

    if share.password_hash:
        # bcrypt has a 72-byte input limit; reject oversized UTF-8 values rather than
        # silently comparing only a truncated prefix.
        if password is not None and len(password.encode("utf-8")) > 72:
            raise HTTPException(status_code=401, detail="A valid share password is required")
        if password is None or not verify_password(password, share.password_hash):
            raise HTTPException(status_code=401, detail="A valid share password is required")

    scan = db.query(models.ScanResult).filter(models.ScanResult.id == share.scan_id).first()
    if not scan:
        raise HTTPException(status_code=404, detail="Shared report not found or expired")
    return scan


